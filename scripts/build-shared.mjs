// Bundle the rules engine into one ES module the Supabase server functions
// (Deno) can import: supabase/functions/_shared/engine.js.
// Run after changing packages/engine:  npm run build:functions
// A test fails if the committed bundle is out of date.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export async function bundleEngine() {
  const root = fileURLToPath(new URL('..', import.meta.url));
  const out = await build({
    absWorkingDir: root, // same output wherever it's run from
    entryPoints: ['packages/engine/src/index.ts'],
    bundle: true, format: 'esm', target: 'es2022', platform: 'neutral', write: false, legalComments: 'none',
  });
  return '// Generated by scripts/build-shared.mjs from packages/engine. Do not edit.\n' + out.outputFiles[0].text.replace(/\r\n/g, '\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = fileURLToPath(new URL('../supabase/functions/_shared/engine.js', import.meta.url));
  writeFileSync(target, await bundleEngine());
  console.log('wrote', target);
}
